def ip_local():
    """IP de esta máquina en la red Wi-Fi (la que usa el teléfono para llegar).

    Conectar un socket UDP no envía nada: solo hace que el sistema elija la
    interfaz de salida, y de ahí se lee la IP.
    """
    try:
        with socket.socket(socket.AF_INET, socket.SOCK_DGRAM) as s:
            s.connect(('8.8.8.8', 80))
            return s.getsockname()[0]
    except OSError:
        return None


# CORS: solo lo necesita la app móvil cuando corre en el navegador
# (npx expo start --web, puerto 8081). La app nativa no pasa por CORS.
# En producción, con esquema y separados por coma: https://app.ejemplo.com
if DEBUG:
    CORS_ALLOWED_ORIGINS = ['http://localhost:8081', 'http://127.0.0.1:8081']
    ip = ip_local()
    if ip:
        CORS_ALLOWED_ORIGINS.append(f'http://{ip}:8081')
    # Para probar la app desde el celular en la red de casa, en cualquier
    # puerto. Solo en desarrollo: en producción la red local no existe.
    CORS_ALLOWED_ORIGIN_REGEXES = [
        r'^http://(localhost|127\.0\.0\.1|192\.168\.\d+\.\d+)(:\d+)?$',
    ]
    for host in ('localhost', '127.0.0.1', '192.168.0.201'):
        if host not in ALLOWED_HOSTS:
            ALLOWED_HOSTS.append(host)
else:
    CORS_ALLOWED_ORIGINS = lista_del_entorno('DJANGO_CORS_ORIGINS')
    # Solo para pruebas: los túneles de Expo cambian de subdominio en cada
    # arranque (ej. ^https://.*\.on\.expo\.app$). Se separan por espacio y no
    # por coma porque una regex puede llevar comas, como \d{1,3}.
    regexes = os.environ.get('DJANGO_CORS_ORIGIN_REGEXES', '').split()
    if regexes:
        CORS_ALLOWED_ORIGIN_REGEXES = regexes
        for regex in regexes:
            # Sin ^ y $, "^https://.*\.expo\.app" también aceptaría
            # https://x.expo.app.sitio-ajeno.com.
            if not (regex.startswith('^') and regex.endswith('$')):
                raise ImproperlyConfigured(
                    f'DJANGO_CORS_ORIGIN_REGEXES: "{regex}" debe empezar con ^ y terminar con $.'
                )
            try:
                re.compile(regex)
            except re.error as error:
                raise ImproperlyConfigured(
                    f'DJANGO_CORS_ORIGIN_REGEXES: "{regex}" no es una regex válida ({error}).'
                )

