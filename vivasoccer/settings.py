# Database
# https://docs.djangoproject.com/en/5.2/ref/settings/#databases

# En la nube la base sale de DATABASE_URL (Neon). Sin ella, en desarrollo se usa
# SQLite local; en producción (DEBUG apagado) es un error de configuración.
if not DEBUG and 'DATABASE_URL' not in os.environ:
    raise ImproperlyConfigured('Falta DATABASE_URL con DEBUG apagado.')

DATABASES = {
    'default': dj_database_url.config(
        default=f"sqlite:///{BASE_DIR / 'db.sqlite3'}",
        conn_max_age=600,
        conn_health_checks=True,
    )
}

# `manage.py test` usa SQLite en memoria: es rápido y nunca toca Neon.
# Con TEST_POSTGRES=1 corre contra DATABASE_URL (Django crea ahí test_<base>).
if sys.argv[1:2] == ['test']:
    if os.environ.get('TEST_POSTGRES') == '1':
        if 'DATABASE_URL' not in os.environ:
            raise ImproperlyConfigured('TEST_POSTGRES=1 necesita DATABASE_URL.')
    else:
        DATABASES = {
            'default': {
                'ENGINE': 'django.db.backends.sqlite3',
                'NAME': ':memory:',
            }
        }


